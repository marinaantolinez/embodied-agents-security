from copy import deepcopy
from datetime import datetime, timezone
from threading import Lock


class AuditLogger:
    """
    Centralized audit logger for security events.

    Events generated by different security components share
    the same chronological audit history.
    """

    def __init__(self):
        self.events = []
        self._lock = Lock()

    def log_event(
        self,
        *,
        tool,
        allowed,
        executed,
        reason,
        arguments=None,
    ):
        """
        Register a security event with a UTC timestamp.
        """

        event = {
            "timestamp": datetime.now(timezone.utc).isoformat(
                timespec="milliseconds"
            ),
            "tool": tool,
            "arguments": deepcopy(arguments),
            "allowed": bool(allowed),
            "executed": bool(executed),
            "reason": reason,
        }

        with self._lock:
            self.events.append(event)

        return deepcopy(event)

    def get_events(self):
        """
        Return a copy of the complete audit history.
        """

        with self._lock:
            return deepcopy(self.events)

    def clear(self):
        """
        Clear the audit history.
        """

        with self._lock:
            self.events.clear()
